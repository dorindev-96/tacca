/// I glifi reali del set "Linear Icons" del file Figma del restyling,
/// estratti da `components/icon-data.js` del progetto di design.
///
/// Perché non `Icons.*` di Material: il set Material ha un'altra costruzione
/// (tratti più spessi, angoli arrotondati, ottica su griglia 24) e accanto
/// alle forme di questo restyling si vede subito che viene da un'altra
/// famiglia. Qui i tracciati sono quelli originali, su griglia 20×20, riempiti
/// con il colore corrente — nessun font di icone da imbarcare.
///
/// Ogni tracciato porta con sé la traslazione che nell'SVG stava in
/// `transform="matrix(1 0 0 1 dx dy)"`.
library;

/// Un `<path>` del glifo: dati SVG (comandi assoluti `M`/`L`/`C`/`Z`),
/// traslazione e regola di riempimento.
class LinearIconPath {
  const LinearIconPath(
    this.d, {
    this.dx = 0,
    this.dy = 0,
    this.evenOdd = false,
  });

  final String d;
  final double dx;
  final double dy;
  final bool evenOdd;
}

/// Un glifo completo, disegnato dentro un quadrato 20×20.
class LinearIconData {
  const LinearIconData(this.paths, {this.quarterTurns = 0});

  final List<LinearIconPath> paths;

  /// Rotazione applicata al disegno. Serve solo alle frecce: nel file di
  /// design la freccia "indietro" è la stessa di "avanti" ruotata di 180°.
  final int quarterTurns;
}

